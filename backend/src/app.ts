import express from 'express';
import { Db } from './db.js';
import { errorHandler } from './http.js';
import { requestRoutes } from './routes/requests.js';
import { visitRoutes } from './routes/visits.js';
import { clinicalRoutes } from './routes/clinical.js';
import { billingRoutes } from './routes/billing.js';
import { catalogRoutes } from './routes/catalog.js';
import { patientAppRoutes } from './routes/patientApp.js';
import { dashboardRoutes } from './routes/dashboard.js';
import { feedbackRoutes } from './routes/feedback.js';
import { consentRoutes } from './routes/consent.js';
import { settingsRoutes } from './routes/settings.js';
import { lifecycleRoutes } from './routes/lifecycle.js';
import { stockRoutes } from './routes/stock.js';
import { einvoiceRoutes } from './routes/einvoice.js';
import { erpRoutes, integrationAdminRoutes } from './routes/erp.js';
import { loadSettings } from './settings.js';

export function createApp(db: Db) {
  loadSettings(db);
  const app = express();
  app.use(express.json({ limit: '1mb' }));
  app.get('/health', (_req, res) => res.json({ ok: true }));
  app.use('/api/requests', requestRoutes(db));
  app.use('/api/visits', visitRoutes(db));
  app.use('/api', clinicalRoutes(db));
  app.use('/api', billingRoutes(db));
  app.use('/api', catalogRoutes(db));
  app.use('/api', patientAppRoutes(db));
  app.use('/api', dashboardRoutes(db), feedbackRoutes(db));
  app.use('/api', consentRoutes(db));
  app.use('/api', settingsRoutes(db));
  app.use('/api', lifecycleRoutes(db));
  app.use('/api', stockRoutes(db));
  app.use('/api', einvoiceRoutes(db));
  app.use('/api', integrationAdminRoutes(db));
  app.use('/api/erp/v1', erpRoutes(db));
  app.use(errorHandler);
  return app;
}
